package engine

import (
	"context"
	"testing"
)

// TestGraderFinanceCases pins the finance masking behaviour against the
// reference dataset of the grading harness. Each case is an input and the
// exact mask the harness expects; a regression here means the detector or the
// engine drifted from the reference.
func TestGraderFinanceCases(t *testing.T) {
	e, _ := newEngine(t)
	for _, tc := range graderFinanceCases {
		t.Run(tc.name, func(t *testing.T) {
			res, err := e.Mask(context.Background(), "", "grader-fin", tc.in)
			if err != nil {
				t.Fatalf("Mask(%q): %v", tc.in, err)
			}
			if res.Output != tc.want {
				t.Errorf("input %q:\n got %q\nwant %q", tc.in, res.Output, tc.want)
			}
		})
	}
}

