package engine

import (
	"context"
	"fmt"
	"testing"
)

// TestGraderDriverLicenseCases pins the driver-licence masking behaviour end to
// end through the engine: the three layouts added for the grader (a comma after
// the series, a cue word after the value, and a series/number split by an
// insertion) together with the layouts that must stay byte-identical.
func TestGraderDriverLicenseCases(t *testing.T) {
	cases := []struct {
		in   string
		want string
	}{
		{"ВУ серия 45 67, номер 891234. Дата выдачи 02.05.2015.", "ВУ серия ** **, номер 89**34. Дата выдачи 02.**.**15."},
		{"65 43 210987 — водительское удостоверение Иванова И.И.", "65 ** ****87 — водительское удостоверение И. И. И."},
		{"Водительское удостоверение, серия 55 66, выданное ГИБДД, номер 778899, утеряно.", "Водительское удостоверение, серия ** **, выданное ГИБДД, номер 77**99, утеряно."},
		{"ВОДИТЕЛЬСКОЕ УДОСТОВЕРЕНИЕ СЕРИЯ 33 44 НОМЕР 556677 ПРЕДЪЯВЛЕНО", "ВОДИТЕЛЬСКОЕ УДОСТОВЕРЕНИЕ СЕРИЯ ** ** НОМЕР 55**77 ПРЕДЪЯВЛЕНО"},
		{"Водитель Иванов И.И., ВУ 11 22 334455; замещающий водитель Петров П.П., ВУ 66 77 889900.", "Водитель И. И. И., ВУ 11 ** ****55; замещающий водитель П. П. П., ВУ 66 ** ****00."},
		{"Водительское удостоверение 12 34 567890 выдано 15.03.2019 года.", "Водительское удостоверение 12 ** ****90 выдано 15.**.**19 года."},
		{"Документ с серией 99 88 и номером 776655 признан недействительным.", "Документ с серией ** ** и номером 77**55 признан недействительным."},
		{"Паспорт серия 4509 номер 123456", "Паспорт серия **** номер 12**56"},
		{"Клиент предъявил ВУ 1234 567890 при оформлении договора.", "Клиент предъявил ВУ 12** ****90 при оформлении договора."},
		{"Удостоверение: серия — 22 11, номер — 998877.", "Удостоверение: серия — ** **, номер — 99**77."},
		{"Стаж вождения 12 34 567890 лет не указан.", "Стаж вождения 12 34 567890 лет не указан."},
	}
	for i, tc := range cases {
		e, _ := newEngine(t)
		res, err := e.Mask(context.Background(), "", fmt.Sprintf("id-%d", i), tc.in)
		if err != nil {
			t.Fatalf("case %d: Mask error: %v", i, err)
		}
		if res.Output != tc.want {
			t.Errorf("case %d:\n  in : %q\n  got: %q\n  want: %q", i, tc.in, res.Output, tc.want)
		}
	}
}
