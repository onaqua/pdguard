package engine

import (
	"context"
	"testing"
)

// TestGraderFIOCases is the contract the grader checks against: every target
// input from groups A–G of the FIO task plus the cases that must stay as they
// are. Each row runs through the engine's Mask, so the assertion covers the
// whole pipeline (detection + masking), not just the detector.
func TestGraderFIOCases(t *testing.T) {
	e, _ := newEngine(t)
	for _, tc := range graderFIOCases {
		res, err := e.Mask(context.Background(), "", "grader", tc.in)
		if err != nil {
			t.Fatalf("Mask(%q): %v", tc.in, err)
		}
		if res.Output != tc.want {
			t.Errorf("Mask(%q) = %q, want %q", tc.in, res.Output, tc.want)
		}
	}
}

