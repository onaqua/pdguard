// TestGraderAddrCases drives the address and citizenship detectors through the
// engine's Mask step and pins the resulting masks. The expected values were
// produced by the real detectors; a mismatch means the detector changed, not
// that the expectation should be edited.
func TestGraderAddrCases(t *testing.T) {
	e, _ := newEngine(t)

	cases := []struct {
		in   string
		want string
	}{
		{
			"город Москва, Кутузовский проспект, дом 36, строение 1, квартира 250",
			"город Мо**ва, Ку*******ий проспект, дом **, строение *, квартира ***",
		},
		{
			"Адрес регистрации: Россия, 119019, г. Москва, ул. Арбат, д. 10, стр. 2, кв. 5.",
			"Адрес регистрации: Ро**ия, 11**19, г. Мо**ва, ул. Ар*ат, д. **, стр. *, кв. *.",
		},
		{
			"пгт им. Воровского, мкр. Заречный, д. 4, к. 2, кв. 15",
			"пгт им. Во******го, мкр. За****ый, д. *, к. *, кв. **",
		},
		{
			"Город проживания — Казань.",
			"Город проживания — Ка**нь.",
		},
		{
			"Я родилась весной. В Москве в то время еще не начинали зеленеть деревья. с 15 августа 2017 я живу в Санкт-Петербурге",
			"Я родилась весной. В Москве в то время еще не начинали зеленеть деревья. с 15 августа 2017 я живу в Са***-********ге",
		},
		{
			"Гражданство бенефициара по договору страхования: Соединенные Штаты Америки.",
			"Гражданство бенефициара по договору страхования: Со********* ***** *****ки.",
		},
		{
			"Гражданство поручителя по договору: Российская Федерация/Армения.",
			"Гражданство поручителя по договору: Ро******** *******ия/Ар***ия.",
		},
		{
			"Ольга Николаевна, просим подойти в отделение банка 20.09.2026 по адресу город Москва, улица Арбат, дом 10",
			"О. Н., просим подойти в отделение банка 20.09.2026 по адресу город Москва, улица Арбат, дом 10",
		},
		{
			"Адрес фактического проживания совпадает с адресом регистрации.",
			"Адрес фактического проживания совпадает с адресом регистрации.",
		},
		{
			"109028, г. Москва, ул. Ленина, д. 1, кв. 10",
			"10**28, г. Мо**ва, ул. Ле**на, д. *, кв. **",
		},
		{
			"г. Санкт-Петербург, Невский пр-кт, д. 25, кв. 7",
			"г. Са***-*******рг, Не***ий пр-кт, д. **, кв. *",
		},
		{
			"с. Павлово, ул. Центральная, д. 3",
			"с. Па***во, ул. Це*******ая, д. *",
		},
		{
			"В карточке клиента указано: гражданство РФ",
			"В карточке клиента указано: гражданство **",
		},
		{
			"Лев Толстой родился в Ясной Поляне.",
			"Лев Толстой родился в Ясной Поляне.",
		},
		{
			"Московская обл., Раменский р-н, д. Никольское",
			"Мо******ая обл., Ра*****ий р-н, д. Ни******ое",
		},
	}

	for _, tc := range cases {
		res, err := e.Mask(context.Background(), "", "grader", tc.in)
		if err != nil {
			t.Fatalf("Mask(%q): %v", tc.in, err)
		}
		if res.Output != tc.want {
			t.Errorf("вход → выход:\n  got  %q\n  want %q", res.Output, tc.want)
		}
	}
}

// TestGraderAddrRegionMarkerKeepsGO checks that the "г.о." marker survives the
// Mask step untouched.
func TestGraderAddrRegionMarkerKeepsGO(t *testing.T) {
	e, _ := newEngine(t)

	in := "Московская обл., Раменский г.о., д. Никольское, ул. Школьная, д. 12"
	res, err := e.Mask(context.Background(), "", "grader-go", in)
	if err != nil {
		t.Fatalf("Mask(%q): %v", in, err)
	}
	if res.Output != "Мо******ая обл., Ра*****ий г.о., д. Ни******ое, ул. Шк****ая, д. **" {
		t.Errorf("вход → выход:\n  got  %q\n  want %q", res.Output, "Мо******ая обл., Ра*****ий г.о., д. Ни******ое, ул. Шк****ая, д. **")
	}
}
